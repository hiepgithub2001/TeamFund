"""Ports: what the use cases need from the outside world, as interfaces.

The infrastructure layer implements them (SQLAlchemy, Fernet, openpyxl, SePay, Telegram), and the
composition root (main.py) plugs the implementations in. Use cases depend only on these."""
from dataclasses import dataclass
from datetime import datetime
from typing import Callable, Protocol

from ..domain.entities import (AuditEntry, Bill, Expense, JobRun, ManagerRequest, Member, Payment, PaymentIntent,
                               Team, TeamAdmin, TeamRequest, User)


class Conflict(Exception):
    """A write broke a uniqueness rule (e.g. a bill for the same member and month, raced)."""


# ---- repositories -------------------------------------------------------------------------------

class Users(Protocol):
    def get(self, tg_id: int) -> User | None: ...
    def add(self, user: User) -> None: ...


class TeamRequests(Protocol):
    def add(self, r: TeamRequest) -> None: ...
    def get(self, request_id: int) -> TeamRequest | None: ...
    def has_pending(self, tg_id: int) -> bool: ...
    def pending(self) -> list[TeamRequest]: ...
    def latest_approved(self, tg_id: int) -> TeamRequest | None: ...


class Teams(Protocol):
    def add(self, team: Team) -> None: ...
    def get(self, team_id: int) -> Team | None: ...
    def bot_exists(self, bot_id: int) -> bool: ...
    def active(self) -> list[Team]: ...
    def for_admin(self, tg_id: int) -> list[tuple[Team, str]]: ...


class Admins(Protocol):
    def add(self, admin: TeamAdmin) -> None: ...
    def get(self, team_id: int, tg_id: int) -> TeamAdmin | None: ...
    def role_of(self, team_id: int, tg_id: int) -> str | None: ...
    def of_team(self, team_id: int) -> list[TeamAdmin]: ...
    def remove(self, admin: TeamAdmin) -> None: ...


class ManagerRequests(Protocol):
    def add(self, r: ManagerRequest) -> None: ...
    def get(self, request_id: int) -> ManagerRequest | None: ...
    def has_pending(self, team_id: int, tg_id: int) -> bool: ...
    def last_rejected_at(self, team_id: int, tg_id: int) -> datetime | None: ...
    def pending(self, team_id: int) -> list[ManagerRequest]: ...
    def expire_created_before(self, cutoff: datetime) -> None: ...


class Members(Protocol):
    def add(self, m: Member) -> None: ...
    def get(self, member_id: int) -> Member | None: ...
    def of_team(self, team_id: int, include_left: bool = False, active_only: bool = False,
                ids: list[int] | None = None) -> list[Member]: ...
    def names(self, member_ids: set[int]) -> list[str]: ...
    def count_by_team(self) -> dict[int, int]: ...


class Bills(Protocol):
    def add(self, b: Bill) -> None: ...
    def get(self, bill_id: int) -> Bill | None: ...
    def get_many(self, bill_ids: list[int], unpaid_only: bool = False) -> list[Bill]: ...
    def unpaid_with_members(self, team_id: int, member_ids: list[int] | None = None) -> list[tuple[Bill, Member]]: ...
    def monthly_with_members(self, team_id: int, period: str, unpaid_only: bool = False) -> list[tuple[Bill, Member]]: ...
    def billed_member_ids(self, team_id: int, period: str) -> set[int]: ...
    def unpaid_of_member(self, member_id: int) -> list[Bill]: ...
    def of_team(self, team_id: int) -> list[Bill]: ...


class Intents(Protocol):
    def add(self, i: PaymentIntent) -> None: ...
    def code_exists(self, code: str) -> bool: ...
    def find_by_codes(self, team_id: int, codes: list[str]) -> PaymentIntent | None: ...
    def expire_pending_before(self, now: datetime) -> None: ...


class Payments(Protocol):
    def add(self, p: Payment) -> None: ...
    def get(self, payment_id: int) -> Payment | None: ...
    def tx_exists(self, tx_id: str) -> bool: ...
    def unmatched(self, team_id: int) -> list[Payment]: ...
    def total(self, team_id: int, start: datetime | None = None, end: datetime | None = None) -> int: ...
    def count_unmatched(self, team_id: int) -> int: ...
    def latest(self, team_id: int, limit: int) -> list[Payment]: ...
    def of_team(self, team_id: int) -> list[Payment]: ...


class Expenses(Protocol):
    def add(self, e: Expense) -> None: ...
    def total(self, team_id: int, start: datetime | None = None, end: datetime | None = None) -> int: ...
    def latest(self, team_id: int, limit: int) -> list[Expense]: ...
    def of_team(self, team_id: int) -> list[Expense]: ...


class Audit(Protocol):
    def add(self, entry: AuditEntry) -> None: ...
    def latest(self, team_id: int, limit: int) -> list[AuditEntry]: ...


class JobRuns(Protocol):
    def exists(self, key: str) -> bool: ...
    def add(self, run: JobRun) -> None: ...


class UnitOfWork(Protocol):
    """One business transaction. `with uow:` ... `uow.commit()`; leaving without commit rolls back."""
    users: Users
    team_requests: TeamRequests
    teams: Teams
    admins: Admins
    manager_requests: ManagerRequests
    members: Members
    bills: Bills
    intents: Intents
    payments: Payments
    expenses: Expenses
    audit: Audit
    job_runs: JobRuns

    def __enter__(self) -> "UnitOfWork": ...
    def __exit__(self, *exc) -> None: ...
    def flush(self) -> None: ...   # assigns ids to new entities; raises Conflict
    def commit(self) -> None: ...  # raises Conflict
    def rollback(self) -> None: ...


# ---- other services -----------------------------------------------------------------------------

class Clock(Protocol):
    def now(self) -> datetime: ...                       # naive UTC, for storing
    def local_now(self) -> datetime: ...                 # the team's local time
    def current_period(self) -> str: ...                 # "YYYY-MM" in local time
    def month_bounds(self, period: str) -> tuple[datetime, datetime]: ...  # UTC [start, end)
    def fmt(self, dt: datetime | None) -> str | None: ...                  # "dd/mm/yyyy HH:MM" local


class TokenCipher(Protocol):
    def encrypt(self, value: str) -> str: ...
    def decrypt(self, value: str) -> str: ...


class PaymentQr(Protocol):
    def url(self, bank_name: str, bank_account: str, amount: int, content: str) -> str: ...


class SepayError(Exception):
    """A SePay API call failed. kind: unauthorized | not_found | invalid | unavailable."""

    def __init__(self, kind: str, message: str = ""):
        super().__init__(f"{kind}: {message}" if message else kind)
        self.kind, self.message = kind, message


@dataclass(frozen=True)
class SepayBankAccount:
    xid: str
    account_number: str
    bank_short_name: str
    bank_code: str
    holder: str
    active: bool


@dataclass(frozen=True)
class SepayWebhook:
    id: str
    url: str


@dataclass(frozen=True)
class SepayWebhookSpec:
    """The one webhook a team needs: incoming money on one bank account, posted to our URL with an API key."""
    name: str
    url: str
    bank_account_xid: str
    api_key: str


class SepayApi(Protocol):
    """The owner's SePay account, reached with an API token they created in my.sepay.vn. Raises SepayError."""
    def bank_accounts(self, token: str) -> list[SepayBankAccount]: ...
    def webhooks(self, token: str) -> list[SepayWebhook]: ...
    def create_webhook(self, token: str, spec: SepayWebhookSpec) -> str: ...
    def update_webhook(self, token: str, webhook_id: str, spec: SepayWebhookSpec) -> None: ...
    def delete_webhook(self, token: str, webhook_id: str) -> None: ...


class SpreadsheetWriter(Protocol):
    def workbook(self, sheets: list[tuple[str, list[str], list[list]]]) -> bytes: ...


class Notifier(Protocol):
    """Sends an event's messages (receipts, group posts, alerts)."""
    def publish(self, event: dict) -> None: ...   # fire and forget
    def deliver(self, event: dict) -> bool: ...   # wait; False if it could not be sent


@dataclass(frozen=True)
class AppConfig:
    public_url: str
    master_admin_ids: tuple[int, ...]
    default_lang: str = "vi"


@dataclass(frozen=True)
class Deps:
    """Everything a use case may use. Built once by the composition root."""
    uow: Callable[[], UnitOfWork]
    clock: Clock
    cipher: TokenCipher
    qr: PaymentQr
    spreadsheet: SpreadsheetWriter
    notifier: Notifier
    config: AppConfig
    sepay: SepayApi
